"""Generate workflow sheets from the three canonical definitions, without service calls."""

import argparse
import json
from pathlib import Path


def render_module(module, catalog, files, limits):
    lines = [f"# {module['title']}", "", "<!-- Generated by contract_docs.py; edit canonical definitions. -->", "",
             "Use the authorized connector. Collect the user's required values; upload local file inputs",
             "and substitute the returned platform references. Submit once, retain the job ID, poll",
             "and inspect all returned artifacts. Never invent inputs or reuse another user's references.", ""]
    entries = [t for t in catalog["tools"].values() if t.get("module_id") == module["id"]]
    for tool in entries:
        job = tool["job_name"]
        schema = tool["request_schema"]
        lines += [f"## {tool['display_name']}", "", tool["description"], ""]
        if tool.get("product_documentation"):
            lines += [f"[Product description and result interpretation](../{tool['product_documentation']})", ""]
        lines += [f"Exact job name: `{job}`.", "", "### Inputs", "",
                  "Fields below belong in `experiment_data`; `experiment_name` is supplied separately.", "",
                  "| Field | Type | Required | Input kind | Description |", "|---|---|---|---|---|"]
        for name, prop in schema["properties"].items():
            notes = prop.get("description", "").replace("|", "\\|").replace("\n", " ")
            kind = prop.get("type", "see schema")
            if isinstance(kind, list):
                kind = " / ".join(kind)
            lines.append(f"| `{name}` | {kind} | {'yes' if name in schema.get('required', []) else 'no / mode-dependent'} | {prop.get('x-input-kind', 'value')} | {notes} |")
        lines += ["", "Input kinds: `value` is inline data; `file` requires a platform file reference;",
                  "`file_or_value` supports either documented mode; `artifact` is an authorized upstream result reference.",
                  "Only local files require a new upload. Never infer input mode from a field name.", "",
                  "### Exact request schema", "", "```json", json.dumps(schema, indent=2, ensure_ascii=False), "```", "",
                  "### Submission envelope", "", "Shape only: replace placeholders with the user's values. This is not a runnable sample.",
                  "```json", json.dumps({"job_name": job, "experiment_name": "<confirmed experiment name>",
                      "experiment_data": {name: f"<user value; see {name} schema>" for name in schema.get('required', [])}}, indent=2), "```", "",
                  "For mode-dependent fields, include the fields required by the selected schema branch.", ""]
        rules = files["tools"].get(job, {}).get("files", {})
        if rules:
            # Full uploaded JSON schemas remain canonical file rules. Their human
            # guide is linked above; avoid duplicating thousands of lines per sheet.
            shown = {name: {k: v for k, v in rule.items() if k not in {"json_schema", "zip_manifest_schema"}}
                     for name, rule in rules.items()}
            lines += ["### File checks", "", "```json", json.dumps(shown, indent=2, ensure_ascii=False), "```", ""]
            if any("json_schema" in rule for rule in rules.values()):
                lines += ["Uploaded JSON content is validated against the full schema in",
                          "`file-input-contracts.v1.json`; see the linked guide for field definitions.", ""]
            if any("zip_manifest_schema" in rule for rule in rules.values()):
                lines += ["The optional ZIP-root ligand manifest shape is canonical in",
                          "`file-input-contracts.v1.json`; see the linked ligand-bundle guide.", ""]
        bounds = limits["tools"].get(job, {})
        if bounds:
            lines += ["### Input limits", "", "```json", json.dumps(bounds, indent=2, ensure_ascii=False), "```", ""]
        if tool.get("review_notes"):
            lines += ["### Execution notices", "", *[f"- {note}" for note in tool["review_notes"]], ""]
        if tool.get("examples"):
            lines += ["### Recorded payload example", "", "Reference only; use current user inputs and upload references.",
                      "```json", json.dumps(tool["examples"], indent=2, ensure_ascii=False), "```", ""]
        lines += ["### Results", "", "Accepted is not completed. Poll the returned job ID without resubmitting.",
                  "Preserve every returned artifact link; download and inspect requested outputs before reporting success.",
                  "Report actual service errors and incomplete outputs. Refresh status for expired links.", ""]
    if not entries:
        lines += ["This is a workflow grouping, not a standalone executable job.", ""]
    return "\n".join(lines).rstrip() + "\n"


def generated_modules(root):
    catalog, files, limits = (json.loads((root / name).read_text(encoding="utf-8-sig")) for name in
                             ("tool-contracts.v1.json", "file-input-contracts.v1.json", "input-limits.v1.json"))
    return {root / module["path"]: render_module(module, catalog, files, limits) for module in catalog["modules"]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).parent / "skills/boltzmann-tools/references"
    stale = []
    for path, content in generated_modules(root).items():
        if args.write:
            path.write_text(content, encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8-sig") != content:
            stale.append(path.name)
    if stale:
        parser.exit(1, "Stale generated modules: " + ", ".join(stale) + "\n")
    print("Contract module sheets are synchronized.")


if __name__ == "__main__":
    main()
