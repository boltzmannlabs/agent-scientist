"""Checks for public BoltPro guide rendering; no service calls are made."""

import copy
import json
from pathlib import Path

from plugins.boltzmann.contract_docs import render_public_tool, render_module


ROOT = Path(__file__).resolve().parents[2] / "plugins/boltzmann/skills/boltzmann-tools/references"


def catalog():
    return json.loads((ROOT / "tool-contracts.v1.json").read_text(encoding="utf-8-sig"))


def test_public_rendering_preserves_contract_and_escapes_table_text():
    tool = {"display_name": "Fixture", "job_name": "fixture", "request_schema": {"type": "object"},
            "public_documentation": {"public_description": "Description", "public_results": "Results",
                                     "fields": [{"name": "example", "type": "string", "required": "Required",
                                                 "input_kind": "value", "description": "A | B\nnext"}]}}
    original = copy.deepcopy(tool)
    result = "\n".join(render_public_tool(tool))
    assert "A \\| B next" in result
    assert "generated by the connector when omitted" in result
    assert tool == original


def test_public_guidance_preserves_exact_schemas_limits_and_execution_notices():
    data = catalog()
    original = copy.deepcopy(data)
    files = json.loads((ROOT / "file-input-contracts.v1.json").read_text(encoding="utf-8-sig"))
    limits = json.loads((ROOT / "input-limits.v1.json").read_text(encoding="utf-8-sig"))
    covered = []
    for module in data['modules']:
        rendered = render_module(module, data, files, limits)
        for tool in data['tools'].values():
            doc = tool.get('public_documentation')
            if tool.get('module_id') != module['id'] or not doc:
                continue
            covered.append(tool['job_name'])
            section = rendered.split(f"## {tool['display_name']}\n", 1)[1].split('\n## ', 1)[0]
            assert doc['public_description'] in section
            assert doc['public_results'] in section
            assert json.dumps(tool['request_schema'], indent=2, ensure_ascii=False) in section
            for field in doc['fields']:
                assert f"`{field['name']}` | {field['type']} | {field['required']} | {field['input_kind']}" in section
            bounds = limits['tools'].get(tool['job_name'])
            if bounds:
                assert json.dumps(bounds, indent=2, ensure_ascii=False) in section
            for note in [*tool.get('review_notes', []), *doc.get('integration_notes', [])]:
                assert note in section
            assert '### Inputs' in section and '### Exact request schema' in section
            assert '<optional; generated if omitted>' in section
            assert 'Choose an experiment name' not in section
    assert set(covered) == {tool['job_name'] for tool in data['tools'].values() if tool.get('public_documentation')}
    assert covered and data == original
